// Farm animals. Shared scenery bits are small string helpers so each page stays compact.
const r = (n) => Math.round(n);

// Scalloped "fluffy" outline around an ellipse (sheep wool, clouds, flower heads).
const fluff = (cx, cy, rx, ry, n) => {
  const pts = Array.from({ length: n }, (_, i) => {
    const a = (i / n) * Math.PI * 2;
    return [r(cx + rx * Math.cos(a)), r(cy + ry * Math.sin(a))];
  });
  const br = r(Math.PI * (rx + ry) / n * 0.62);
  return `<path d="M${pts[0]}${pts.slice(1).concat([pts[0]]).map((p) => `A${br} ${br} 0 0 1 ${p}`).join('')}Z"/>`;
};

// Ground bleeds off the page on three sides.
const ground = (y = 318) => `<path d="M-20 ${y}Q90 ${y - 22} 200 ${y}T420 ${y}V420H-20Z"/>`;
const sun = (x, y) => `<circle cx="${x}" cy="${y}" r="26"/><path class="l" d="M${x} ${y - 36}v-12M${x} ${y + 36}v12M${x - 36} ${y}h-12M${x + 36} ${y}h12M${x - 26} ${y - 26}l-8 -8M${x + 26} ${y - 26}l8 -8M${x - 26} ${y + 26}l-8 8M${x + 26} ${y + 26}l8 8"/>`;
const cloud = (x, y) => fluff(x, y, 40, 18, 9);
// One big scalloped bloom + centre: two colourable parts, none of them crumbs.
const flower = (x, y) => {
  const p = Array.from({ length: 5 }, (_, i) => [r(x + 12 * Math.sin(i * 1.2566)), r(y - 12 * Math.cos(i * 1.2566))]);
  return `<path class="l" d="M${x} ${y + 20}v22"/><path d="M${p[0]}${[...p.slice(1), p[0]].map((q) => `A10 10 0 1 1 ${q}`).join('')}Z"/><circle cx="${x}" cy="${y}" r="9"/>`;
};
const fence = (x0, x1, y) => {
  let s = `<rect x="${x0}" y="${y + 10}" width="${x1 - x0}" height="12" rx="3"/><rect x="${x0}" y="${y + 38}" width="${x1 - x0}" height="12" rx="3"/>`;
  for (let x = x0 + 4; x < x1 - 10; x += 44) s += `<path d="M${x} ${y + 8}l11 -12 11 12V${y + 64}H${x}Z"/>`;
  return s;
};
const eye = (x, y, s = 9) => `<circle cx="${x}" cy="${y}" r="${s}"/><circle class="k" cx="${x + 1}" cy="${y + 1}" r="${s * 0.55}"/>`;
// Hoof/trotter cap under a leg whose bottom edge runs from x0 to x1 at height y.
const hoof = (x0, x1, y, h = 13) => `<path d="M${x0} ${y}H${x1}L${x1 + 2} ${y + h}H${x0 - 2}Z"/>`;
// A far-side leg (drawn before the body, so its top tucks behind it).
const farLeg = (x, top, y, w = 22) => `<path d="M${x} ${top}C${x + 1} ${top + 30} ${x + 3} ${y - 18} ${x + 3} ${y}H${x + w + 1}C${x + w + 1} ${y - 18} ${x + w} ${top + 30} ${x + w} ${top}Z"/>`;

